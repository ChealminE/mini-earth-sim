//   예전엔 조감 모드가 관측치 선형회귀, 1인칭 모드가 따로 만든 곡선을 썼다.
//   418ppm까지는 우연히 비슷했지만 1000ppm에서 pH가 7.50 vs 6.15로 갈라졌다.
//   같은 프로그램 안에서 학생이 잰 값과 예측 탭 값이 다르면 도구를 못 믿는다.
//
