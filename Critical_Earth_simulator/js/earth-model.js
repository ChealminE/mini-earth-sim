// ── 슬라이더 공통 범위 ──────────────────────────────────────────────────────
// 두 모드가 같은 축을 쓰게 맞춰 둔다. 280 = 산업화 이전, 418 = 2023년 관측치.
const CO2_MIN = 280, CO2_MAX = 1000, CO2_NOW = 418;

// ============================================================================
// 1) 해수 pH - 탄산 평형에서 직접 계산
// ----------------------------------------------------------------------------
// 예전엔 관측치 35점에 직선을 맞춰 썼다(pH = -0.000942·CO2 + 8.441). 관측 구간
// (350~418ppm)에서는 잘 맞지만 그 밖으로 끌고 가면 근거가 없다. 직선이니까
// CO2를 계속 올리면 pH가 한없이 내려가는데, 실제 바다는 그렇게 되지 않는다.
//
// 대신 실제로 일어나는 반응을 그대로 푼다:
//     CO2(g) ⇌ CO2(aq)              [CO2*] = K0 · pCO2        (헨리 법칙)
//     CO2* + H2O ⇌ H+ + HCO3-       K1 = [H+][HCO3-] / [CO2*]
//     HCO3-     ⇌ H+ + CO3^2-       K2 = [H+][CO3^2-] / [HCO3-]
//
// 여기에 '총알칼리도(TA)는 변하지 않는다'는 조건을 건다. 바다에 녹아드는 CO2는
// 양이온 균형을 바꾸지 않기 때문에 이 가정이 성립한다.
//     TA ≈ [HCO3-] + 2[CO3^2-]
// 두 농도를 [H+]로 정리해 넣으면 [H+]에 대한 2차방정식이 되어 근의 공식으로 풀린다:
//     TA·h² - C·h - 2·C·K2 = 0,   C = K0·K1·pCO2
//
// 이렇게 얻은 곡선은 관측 35점을 RMSE 0.007 (최대오차 0.013)로 맞춘다.
// 회귀로 맞춘 게 아니라 화학 상수만 넣었는데 관측과 겹친다는 점이 이 모형의 요지다.
// 곡선이 아래로 휘는 이유(= 완충)도 식에서 바로 설명된다.
const OCEAN_TA = 2.3e-3;    // 총알칼리도 [mol/kg] - 표층 해수 대표값
const OCEAN_K0 = 0.0283;    // CO2 용해도 [mol/(kg·atm)]  25°C, 염분 35
const OCEAN_K1 = 1.42e-6;   // 1차 해리상수  (pK1 ≈ 5.85)
const OCEAN_K2 = 1.08e-9;   // 2차 해리상수  (pK2 ≈ 8.97)

function seawaterPH(ppm) {
  const pCO2 = Math.max(1, ppm) * 1e-6;              // ppm -> atm
  const C = OCEAN_K0 * OCEAN_K1 * pCO2;
  const h = (C + Math.sqrt(C * C + 8 * OCEAN_TA * C * OCEAN_K2)) / (2 * OCEAN_TA);
  return -Math.log10(h);
}

// 아라고나이트 포화도 Ω - 산호·조개가 골격을 만들 수 있는지를 결정하는 값.
// Ω < 1이면 이미 만든 탄산칼슘 골격이 녹기 시작한다. 백화(수온 문제)와는 다른 현상이라
// 따로 계산해서 따로 보여준다.
//     Ω = [Ca2+][CO3^2-] / Ksp
// [Ca2+]는 해수에서 거의 일정(0.0103 mol/kg)하므로 [CO3^2-]만 pH에서 구하면 된다.
const OCEAN_CA = 0.0103;    // [mol/kg]
const ARAGONITE_KSP = 6.65e-7;
function aragoniteOmega(ppm) {
  const pCO2 = Math.max(1, ppm) * 1e-6;
  const h = Math.pow(10, -seawaterPH(ppm));
  const co3 = OCEAN_K0 * OCEAN_K1 * OCEAN_K2 * pCO2 / (h * h);
  return OCEAN_CA * co3 / ARAGONITE_KSP;
}

// ============================================================================
// 2) 기온 편차 - 관측치를 '로그 형태'로 회귀
// ----------------------------------------------------------------------------
// 예전엔 CO2에 직선을 맞췄다(dT = 0.01608·CO2 - 6.101). 관측 구간에서는 r=0.925로
// 잘 맞지만, 복사강제력은 농도가 아니라 농도의 로그에 비례한다. 그래서 직선을
// 1000ppm까지 끌고 가면 +9.98°C라는 과한 값이 나온다.
//
// 같은 36개 관측점에 dT = λ·log2(CO2/280) + b 형태로 다시 맞췄다.
// 상관계수는 r=0.924로 사실상 그대로인데(설명력을 잃지 않았다는 뜻),
// 1000ppm 외삽은 +5.96°C로 내려온다.
//
// λ = 4.26°C/배증 = 이 관측 기록에서 읽어낸 '기후 민감도'.
// IPCC 최적 추정치는 3.0°C(가능 범위 2.5~4.0)다. 36년치 짧은 기록이라 값이 조금
// 높게 나오는데, 이 차이 자체가 "짧은 기록으로 외삽할 때 무엇을 조심해야 하는가"를
// 이야기할 거리가 된다. 여기서는 관측에서 나온 값을 그대로 쓴다.
const CLIMATE_LAMBDA = 4.2580;    // °C per CO2 doubling
const CLIMATE_OFFSET = -1.8579;   // 1991-2020 평년 기준으로 맞춘 절편
const IPCC_LAMBDA_RANGE = [2.5, 4.0];

// 1991-2020 평년 대비 기온 편차 [°C]
function climateAnomaly(ppm) {
  return CLIMATE_LAMBDA * Math.log2(Math.max(1, ppm) / 280) + CLIMATE_OFFSET;
}
// 산업화 이전(280ppm) 대비 승온 - 1인칭 지면·대기 온도가 이 값을 기준으로 오른다
function warmingSince280(ppm) {
  return climateAnomaly(ppm) - climateAnomaly(280);
}
