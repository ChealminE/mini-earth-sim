// ── 슬라이더 공통 범위 ──────────────────────────────────────────────────────
// 두 모드가 같은 축을 쓰게 맞춰 둔다. 280 = 산업화 이전, 418 = 2023년 관측치.
const CO2_MIN = 280, CO2_MAX = 1000, CO2_NOW = 418;

// ============================================================================
// 1) 해수 pH - 탄산 평형에서 직접 계산
// ----------------------------------------------------------------------------
// 예전엔 관측치 35점에 직선을 맞춰 썼다(pH = -0.000942·CO2 + 8.441). 관측 구간
// (350~418ppm)에서는 잘 맞지만 그 밖으로 끌고 가면 근거가 없다. 직선이니까
// CO2를 계속 올리면 pH가 한없이 내려가는데, 실제 바다는 그렇게 되지 않는다.
//
// 대신 실제로 일어나는 반응을 그대로 푼다:
//     CO2(g) ⇌ CO2(aq)              [CO2*] = K0 · pCO2        (헨리 법칙)
//     CO2* + H2O ⇌ H+ + HCO3-       K1 = [H+][HCO3-] / [CO2*]
//     HCO3-     ⇌ H+ + CO3^2-       K2 = [H+][CO3^2-] / [HCO3-]
//
// 여기에 '총알칼리도(TA)는 변하지 않는다'는 조건을 건다. 바다에 녹아드는 CO2는
// 양이온 균형을 바꾸지 않기 때문에 이 가정이 성립한다.
//     TA ≈ [HCO3-] + 2[CO3^2-]
// 두 농도를 [H+]로 정리해 넣으면 [H+]에 대한 2차방정식이 되어 근의 공식으로 풀린다:
//     TA·h² - C·h - 2·C·K2 = 0,   C = K0·K1·pCO2
//
// 이렇게 얻은 곡선은 관측 35점을 RMSE 0.008 (최대오차 0.015)로 맞춘다.
// 회귀로 맞춘 게 아니라 화학 상수만 넣었는데 관측과 겹친다는 점이 이 모형의 요지다.
// 곡선이 아래로 휘는 이유(= 완충)도 식에서 바로 설명된다.
//
// 기본 수온을 25 °C로 두는 이유: 검증에 쓴 관측 35점이 하와이 ALOHA(HOT) 해역
// 자료이고, 그 해역 표층 수온이 실제로 약 25 °C다. 즉 "관측 RMSE가 가장 작아지는
// 수온"을 고른 게 아니라 "관측이 이뤄진 해역의 수온"을 넣은 것이다. RMSE만 보면
// 18~20 °C가 0.0070으로 더 낮지만, 그렇게 고르는 순간 이 모형은 다시 관측에
// 맞춘 회귀가 되어 버린다. 그래서 0.008을 그대로 받아들인다.
//
// ── 평형상수는 수온의 함수다 ────────────────────────────────────────────────
// 예전엔 25 °C 값 하나를 상수로 박아 뒀다. 그러면 빙하 앞 2 °C 바다와 적도
// 바다가 같은 답을 내서, 르샤틀리에 원리나 헨리 법칙이 등장할 자리가 없다.
// 문헌식으로 바꾼다 (염분 S는 35로 고정, TA 일정 가정은 그대로):
//   K0  (CO2 용해도, 헨리 상수)      : Weiss (1974)
//   K1·K2 (탄산 1·2차 해리, total scale): Lueker et al. (2000)
//   Ksp (아라고나이트)               : Mucci (1983)
// TA 일정 모형에서는 수온이 올라가면 K0은 줄고 K1·K2는 커져 효과가 거의 상쇄되므로
// pH 차이는 0.016 정도로 작다. 수온의 주 신호는 pH가 아니라 용존 CO2와 Ω로 나온다.
const OCEAN_TA = 2.3e-3;    // 총알칼리도 [mol/kg] - 표층 해수 대표값
const OCEAN_S = 35;         // 염분 [PSU] - 표층 해수 대표값으로 고정
const OCEAN_CA = 0.0103;    // [Ca2+] [mol/kg] - 해수에서 거의 일정
const T_REF = 25;           // 기본 수온 [°C] - HOT 검증 해역. 기존 호출부의 기본값

function carbonateConstants(tC, S = OCEAN_S) {
  const T = tC + 273.15;                              // °C -> K
  const K0 = Math.exp(-60.2409 + 93.4517 * (100 / T) + 23.3585 * Math.log(T / 100)
             + S * (0.023517 - 0.023656 * (T / 100) + 0.0047036 * (T / 100) ** 2));
  const pK1 = 3633.86 / T - 61.2172 + 9.67770 * Math.log(T) - 0.011555 * S + 0.0001152 * S * S;
  const pK2 = 471.78 / T + 25.9290 - 3.16967 * Math.log(T) - 0.01781 * S + 0.0001122 * S * S;
  const logKsp = -171.945 - 0.077993 * T + 2903.293 / T + 71.595 * Math.log10(T)
               + (-0.068393 + 0.0017276 * T + 88.135 / T) * Math.sqrt(S)
               - 0.10018 * S + 0.0059415 * S ** 1.5;
  return { K0, K1: 10 ** -pK1, K2: 10 ** -pK2, KspAr: 10 ** logKsp };
}

// 해수 상태를 한 번에 푼다. pH·용존CO2·HCO3-·CO3^2-·DIC·Ω를 같은 풀이에서 뽑으므로
// 서로 어긋날 일이 없다. 아라고나이트 포화도 Ω = [Ca2+][CO3^2-] / Ksp 이고,
// Ω < 1이면 이미 만들어진 탄산칼슘 골격이 녹기 시작한다(백화와는 다른 현상).
// 농도 단위는 전부 mol/kg.
function seawaterState(ppm, tC = T_REF, TA = OCEAN_TA) {
  const c = carbonateConstants(tC);
  const pCO2 = Math.max(1, ppm) * 1e-6;               // ppm -> atm
  const co2aq = c.K0 * pCO2;                          // 헨리 법칙
  const C = co2aq * c.K1;
  const h = (C + Math.sqrt(C * C + 8 * TA * C * c.K2)) / (2 * TA);
  const hco3 = C / h;
  const co3 = C * c.K2 / (h * h);
  return {
    pH: -Math.log10(h),
    co2aq, hco3, co3,
    dic: co2aq + hco3 + co3,
    omega: OCEAN_CA * co3 / c.KspAr,
  };
}

// 기존 이름 유지 - 인자 하나로 부르던 호출부는 25 °C 기준으로 그대로 동작한다.
function seawaterPH(ppm, tC = T_REF) { return seawaterState(ppm, tC).pH; }
function aragoniteOmega(ppm, tC = T_REF) { return seawaterState(ppm, tC).omega; }

// ── 역방향: DIC가 주어졌을 때 표층 해수의 pCO2 ────────────────────────────────
// seawaterState()는 "대기 CO2가 이만큼이면 바다가 평형일 때 어떤가"를 푼다.
// 지구 시스템 엔진(js/earth-system.js)은 반대로, 바다가 실제로 품고 있는 탄소(DIC)를
// 적분하면서 "그 바다가 내뿜으려는 CO2 분압"을 알아야 대기와의 교환량을 계산할 수 있다.
// 같은 가정(TA = [HCO3-] + 2[CO3^2-], 붕산염 없음)에서 DIC를 고정하면
//     TA·h² + (TA−DIC)·K1·h + (TA−2·DIC)·K1·K2 = 0
// 이 되어 역시 근의 공식으로 풀린다 (tools/earth_system_ref/engine.py의 pco2_from_dic과 같은 식).
// seawaterState(p, t).dic을 넣으면 p가 그대로 되돌아온다 (상대오차 1e-9 이내).
function pco2FromDic(dic, tC, TA = OCEAN_TA) {
  const c = carbonateConstants(tC);
  const a = TA, b = (TA - dic) * c.K1, cc = (TA - 2 * dic) * c.K1 * c.K2;
  const h = (-b + Math.sqrt(b * b - 4 * a * cc)) / (2 * a);
  const den = h * h + c.K1 * h + c.K1 * c.K2;
  const co2aq = dic * h * h / den;
  const hco3 = dic * c.K1 * h / den;
  const co3 = dic * c.K1 * c.K2 / den;
  return {
    pco2: co2aq / c.K0 * 1e6,                          // atm -> ppm
    pH: -Math.log10(h),
    omega: OCEAN_CA * co3 / c.KspAr,
    co2aq, hco3, co3,
  };
}

// 복사강제력 [W/m²] - CO2가 기준 농도 c0 대비 얼마나 열을 더 가두는가.
// 농도가 아니라 농도의 로그에 비례한다 (Myhre et al. 1998의 단순식).
function radiativeForcing(ppm, c0) {
  return 5.35 * Math.log(ppm / c0);
}

// Revelle 계수 = (ΔpCO2/pCO2) / (ΔDIC/DIC). "바다의 완충 능력"의 역수 같은 값이다.
// 이 값이 클수록 대기 CO2가 늘어도 바다가 그만큼 덜 받아 준다.
// engine.py의 revelle()과 같은 수치미분(1 ppm 차분).
function revelleFactor(ppm, tC) {
  const d = 1.0;
  const a = seawaterState(ppm, tC).dic;
  const b = seawaterState(ppm + d, tC).dic;
  return (d / ppm) / ((b - a) / a);
}

// 바다의 완충 능력 - 기준 시점(보통 1750년) 대비 상대값 (1 = 그때와 같음).
// 화면에는 이 상대값(%)만 쓴다. 이 모형은 붕산염 알칼리도를 빼서 TA를 탄산염만으로
// 두기 때문에 Revelle 계수 절댓값이 12~20으로 실제 바다(약 10)보다 높게 나온다.
// 절댓값은 틀리지만 "얼마나 나빠졌나"라는 변화 비율은 붕산염 유무에 덜 민감하므로
// 비율로만 보여 준다.
function bufferCapacityRel(ppm, tC, refPpm, refTC) {
  return revelleFactor(refPpm, refTC) / revelleFactor(ppm, tC);
}

// ============================================================================
// 2) 기온 편차 - 관측치를 '로그 형태'로 회귀
// ----------------------------------------------------------------------------
// 예전엔 CO2에 직선을 맞췄다(dT = 0.01608·CO2 - 6.101). 관측 구간에서는 r=0.925로
// 잘 맞지만, 복사강제력은 농도가 아니라 농도의 로그에 비례한다. 그래서 직선을
// 1000ppm까지 끌고 가면 +9.98°C라는 과한 값이 나온다.
//
// 같은 36개 관측점에 dT = λ·log2(CO2/280) + b 형태로 다시 맞췄다.
// 상관계수는 r=0.924로 사실상 그대로인데(설명력을 잃지 않았다는 뜻),
// 1000ppm 외삽은 +5.96°C로 내려온다.
//
// λ = 4.26°C/배증 = 이 관측 기록에서 읽어낸 '기후 민감도'.
// IPCC 최적 추정치는 3.0°C(가능 범위 2.5~4.0)다. 36년치 짧은 기록이라 값이 조금
// 높게 나오는데, 이 차이 자체가 "짧은 기록으로 외삽할 때 무엇을 조심해야 하는가"를
// 이야기할 거리가 된다. 여기서는 관측에서 나온 값을 그대로 쓴다.
const CLIMATE_LAMBDA = 4.2580;    // °C per CO2 doubling
const CLIMATE_OFFSET = -1.8579;   // 1991-2020 평년 기준으로 맞춘 절편
const IPCC_LAMBDA_RANGE = [2.5, 4.0];

// 1인칭 모드 전용으로 남겨 둔 회귀식. 조감 모드는 js/earth-system.js의 2층 에너지 균형 모델을 쓴다.
// 3단계(1인칭 연동)에서 교체 예정.
// 1991-2020 평년 대비 기온 편차 [°C]
function climateAnomaly(ppm) {
  return CLIMATE_LAMBDA * Math.log2(Math.max(1, ppm) / 280) + CLIMATE_OFFSET;
}
// 1인칭 모드 전용으로 남겨 둔 회귀식. 조감 모드는 js/earth-system.js의 2층 에너지 균형 모델을 쓴다.
// 3단계(1인칭 연동)에서 교체 예정.
// 산업화 이전(280ppm) 대비 승온 - 1인칭 지면·대기 온도가 이 값을 기준으로 오른다
function warmingSince280(ppm) {
  return climateAnomaly(ppm) - climateAnomaly(280);
}

